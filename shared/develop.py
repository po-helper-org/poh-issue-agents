"""Контракт передачи задачи в разработку — активность Develop.

Research доводит Issue до системных требований и метки `ready-for-dev` (точка
передачи H1 протокола). Develop — второй ключевой шаг: взять подготовленный
Issue и довести его до открытого PR. Код пишет внешний агент (OpenHands
Resolver в GitHub Actions), а этот модуль описывает ровно границу между ним и
циклом: чем прогон запускается, что ему передаётся и что он обязан доложить
обратно.

Почему `workflow_dispatch`, а не метка-триггер. Метка — состояние, а не
событие: повторная постановка не запускает ничего (GitHub не шлёт `labeled` на
уже висящую метку), снятая руками метка теряет запуск молча, а два цикла по
соседним Issue неразличимы в логе Actions. Диспатч — именно событие, у него
есть возвращаемый идентификатор прогона и явные входы. Метка остаётся, но как
индикатор для человека, а не как транспорт.

Почему цикл не ждёт результат в активности. Прогон OpenHands идёт десятки
минут, и активность, которая столько висит на heartbeat, ничего не добавляет:
результат всё равно приходит событием (`POST /agent-event`, фаза `pr-open`).
Активность отвечает только за «запуск состоялся», дальше цикл паркуется в фазе
`in-development` — ожидание здесь такое же первоклассное состояние, как
ожидание человека.

Модуль намеренно чистый: ни сети, ни Temporal, ни GitHub — как
`shared/lifecycle.py` и `shared/agent_events.py`.
"""

import os

# Файл workflow в репозитории-цели. Диспатчится по имени файла, а не по имени
# workflow: имя внутри файла человек меняет свободно, путь — контракт.
DEFAULT_WORKFLOW_FILE = "openhands-resolver.yml"

# Ветка, из которой берётся сам workflow (не ветка работы — её заводит агент).
DEFAULT_REF = "main"

# Метка-индикатор для человека: видно в списке Issue, что задача уехала в
# разработку, не открывая Actions. Пишет её Issue-Agent — метка его зоны.
IN_DEVELOPMENT_LABEL = "in-development"

# Имя, которым внешний агент подписывается в `/agent-event`. Одно на весь
# контур: по нему в таймлайне отличается работа Develop от работы PR-Agent.
AGENT_NAME = "openhands"


def workflow_file() -> str:
    return os.environ.get("DEVELOP_WORKFLOW_FILE", "").strip() or DEFAULT_WORKFLOW_FILE


def workflow_ref() -> str:
    return os.environ.get("DEVELOP_REF", "").strip() or DEFAULT_REF


def enabled() -> bool:
    """Выключатель контура разработки.

    Пусто — включено: демо-контур замкнут по умолчанию, иначе забытая
    переменная тихо обрывает путь на самом дорогом шаге. Явное `0`/`false`
    оставляет Issue в `ready-for-dev`, то есть в очереди к живому разработчику,
    — это и есть поведение до появления Develop.
    """
    raw = os.environ.get("DEVELOP_ENABLED", "").strip().lower()
    return raw not in {"0", "false", "no", "off"}


def dispatch_inputs(issue_number: int, *, branch: str, priority: str = "") -> dict[str, str]:
    """Входы прогона. Только строки: `workflow_dispatch` других не принимает.

    `research_branch` передаётся отдельным входом, хотя агент мог бы вывести имя
    по конвенции. Конвенция — наша, а не его: она меняется у нас и ломала бы
    чужой прогон молча. Пустая строка означает «аналитики не было» (путь бага),
    и агент обязан отличать её от несуществующей ветки.
    """
    return {
        "issue_number": str(issue_number),
        "research_branch": branch or "",
        "priority": priority or "",
    }


def handoff_comment(issue_number: int, *, repo: str, branch: str) -> str:
    """Комментарий в Issue о старте разработки.

    Называет, что именно уехало в работу и где смотреть прогон: человек, который
    открыл Issue, не должен искать по Actions, какой из прогонов его.
    """
    artifacts = (f"- контекст для агента: ветка `{branch}`\n"
                 if branch else
                 "- аналитики по задаче не было — агент работает от тела Issue\n")
    return (
        "🛠 Передал задачу в разработку — запустил OpenHands Resolver.\n\n"
        f"{artifacts}"
        f"- прогон: https://github.com/{repo}/actions/workflows/{workflow_file()}\n"
        "- найденные по дороге edge-кейсы агент заводит отдельными SubIssue, "
        "а не чинит в этой же ветке\n\n"
        "Задача останется в фазе `in-development`, пока агент не доложит об "
        f"открытом PR (`Closes #{issue_number}`)."
    )
