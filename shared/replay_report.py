"""Разбор и показ отказов реплея — общий для обоих инструментов.

Реплей историй делают двое: `scripts/replay_histories.py` по снятому корпусу и
`scripts/deploy_guard.py --replay` по живым прогонам из Temporal. Группировка
отказов и форма отчёта у них обязаны совпадать — иначе одна и та же поломка
выглядит по-разному в зависимости от того, каким инструментом её нашли, и
правку приходится вносить дважды.

Модуль чистый: ни Temporal, ни сети, ни импорта воркера. Это важно не только
для тестов — быстрый режим сторожа обязан работать там, где зависимостей
воркера нет, а `replay_histories` тянет `workflows` уже в шапке.
"""
from __future__ import annotations

# Начало различающей части в тексте отказа Temporal. До него — общая обёртка,
# одинаковая у всех расхождений.
MARKER = "Nondeterminism error: "

# Потолок ключа группировки. Полный текст несёт идентификаторы прогона, и с ними
# каждая строка уникальна — группировка выродилась бы в список.
_KEY_LEN = 160

# Сколько прогонов показать в группе: группа нужна числом, а не перечислением.
_SHOWN_PER_GROUP = 5


def failure_reason(exc: BaseException, marker: str = MARKER) -> str:
    """Во что группировать отказ реплея.

    У расхождения берём хвост после маркера: в начале текста стоит общая для
    всех обёртка, а различает причины именно то, что после него («Activity
    machine does not handle this event» против «Timer machine…»).

    Отказ не про недетерминизм (история не той версии, класс воркфлоу не
    зарегистрирован) группируем по типу исключения: осмысленного текста,
    который стоило бы показывать, у него обычно нет.
    """
    text = str(exc)
    return text.split(marker)[-1][:_KEY_LEN] if marker in text else type(exc).__name__


def format_failures(failures: dict[str, list[str]]) -> list[str]:
    """Строки отчёта по сгруппированным отказам, частое — выше.

    Порядок по убыванию размера группы, а не по алфавиту: одна выкладка ломает
    десятки прогонов по одной причине, и вторая, более редкая причина обязана
    быть видна рядом, а не потеряться в конце.
    """
    lines = []
    for reason, ids in sorted(failures.items(), key=lambda kv: -len(kv[1])):
        lines.append(f"  {len(ids):3d}  {reason}")
        for workflow_id in ids[:_SHOWN_PER_GROUP]:
            lines.append(f"         {workflow_id}")
        if len(ids) > _SHOWN_PER_GROUP:
            lines.append(f"         … и ещё {len(ids) - _SHOWN_PER_GROUP}")
    return lines
