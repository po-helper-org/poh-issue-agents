"""Подпись под комментариями сервиса — чтобы он не принимал их за ответ человека.

Найдено на живом прогоне: оба сигнала `user_comment` в истории цикла оказались
нашими же комментариями — advisor-ответом и разбором приоритета. Гейт вебхука
на `comment.user.type == "Bot"` их не отсекает, потому что сервис ходит в GitHub
под PAT, а не как GitHub App, и его комментарии приходят с `type == "User"`.

Почему подпись, а не логин. Владелец PAT — живой человек, и он же заводит Issue
и отвечает на уточняющие вопросы. Фильтр по логину выкинул бы вместе с нашими
комментариями его настоящие ответы — то есть сломал бы цикл уточнений ради
починки самоподдува. Подпись различает не автора, а происхождение, и работает
одинаково при обеих схемах авторизации.

Маркер невидим в отрендеренном Markdown: GitHub не показывает HTML-комментарии.
"""

MARKER = "<!-- issue-agent -->"


def sign(body: str) -> str:
    """Добавляет подпись, если её ещё нет.

    Идемпотентность важна: один и тот же текст может пройти через несколько
    слоёв (например, шаблон уже подписан, а отправляет его общий post_comment).
    """
    if MARKER in body:
        return body
    return f"{body}\n\n{MARKER}"


def is_agent_comment(body: str | None) -> bool:
    return MARKER in (body or "")
