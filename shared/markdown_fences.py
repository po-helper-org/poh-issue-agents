"""Маскировка блоков кода в Markdown-тексте.

Общий примитив для любого разбора, которому нельзя путать иллюстрацию внутри
тройных обратных кавычек с настоящим содержимым документа: пример или
шаблон, процитированный где-то внутри текста, не должен читаться как
настоящий заголовок, раздел или объявленная зависимость. Используется и
`worker.activities._howtodemo_block` (сценарий приёмки из тела Issue), и
`shared.plan_parse` (шаги плана и их Consumes).

Модуль намеренно чистый: ни сети, ни файлов, ни Temporal — как весь `shared/`.
"""

import re

# Забор — РОВНО три кавычки — не понимал ни забор из четырёх и более
# (стандартный способ процитировать текст, где уже есть тройные кавычки —
# иначе цитата закрылась бы раньше своей внутренней тройной кавычки), ни
# незакрытый забор. Обе формы оставались НЕ помаскированными (у первой —
# потому что паттерн требовал закрытия РОВНО тремя кавычками, а такой строки
# в тексте могло не быть вовсе; у второй — потому что `.sub` не находит
# совпадение без закрывающей части и не трогает текст).
#
# `(?P<fence>`{3,})` — открывающий забор ЛЮБОЙ длины от трёх кавычек, а не
# фиксированной. Закрывающий — обратная ссылка на тот же символ `(?P=fence)`
# плюс `` `* `` следом: ровно то же требование, что и у Markdown-спеки —
# «не короче открывающего», а не «столько же». Короткий забор ПОСЕРЕДИНЕ
# блока (например, тройные кавычки внутри забора из четырёх) под это
# требование не подходит и закрытием не считается — блок остаётся открытым.
# `|\Z` — единственная альтернатива, которая гарантированно совпадёт, если
# закрывающего забора в тексте больше не найдётся: незакрытый забор считается
# открытым до конца текста, а не пропускается маскировкой вовсе.
_CODE_FENCE = re.compile(
    r"(?ms)^[ \t]*(?P<fence>`{3,})[^\n]*\n"
    r".*?"
    r"(?:^[ \t]*(?P=fence)`*[ \t]*$|\Z)"
)


def mask_code_fences(text: str) -> str:
    """Стирает содержимое ``` блоков пробелами той же длины (переводы строк
    сохраняются), чтобы смещения символов не съезжали — маску можно искать
    регэкспами, рассчитанными на исходный текст, и переиспользовать найденные
    позиции для среза из ОРИГИНАЛА. Маска нужна только для ПОИСКА границ —
    реальное содержимое настоящего раздела вырезается из исходного текста, а
    не из маски, поэтому настоящий пример внутри настоящего раздела (например,
    curl-запрос в шаге демонстрации) не теряется."""
    text = text or ""
    return _CODE_FENCE.sub(
        lambda m: "".join(ch if ch == "\n" else " " for ch in m.group(0)), text)
