"""Маскировка блоков кода в Markdown-тексте.

Общий примитив для любого разбора, которому нельзя путать иллюстрацию внутри
тройных обратных кавычек с настоящим содержимым документа: пример или
шаблон, процитированный где-то внутри текста, не должен читаться как
настоящий заголовок, раздел или объявленная зависимость. Используется и
`worker.activities._howtodemo_block` (сценарий приёмки из тела Issue), и
`shared.plan_parse` (шаги плана и их Consumes).

Модуль намеренно чистый: ни сети, ни файлов, ни Temporal — как весь `shared/`.
"""

import re

# Забор — РОВНО три кавычки/тильды — не понимал ни забор из четырёх и более
# (стандартный способ процитировать текст, где уже есть тройные кавычки —
# иначе цитата закрылась бы раньше своей внутренней тройной кавычки), ни
# незакрытый забор. Обе формы оставались НЕ помаскированными (у первой —
# потому что паттерн требовал закрытия РОВНО тремя кавычками, а такой строки
# в тексте могло не быть вовсе; у второй — потому что `.sub` не находит
# совпадение без закрывающей части и не трогает текст).
#
# Теперь поддерживаем оба типа забора: backticks (`) и tildes (~). Каждый
# regex требует, чтобы открывающий и закрывающий заборы были одного типа.
#
# `(?P<fence>`{3,}|~{3,})` — открывающий забор из трёх или более символов
# ЛЮБОЙ длины (ровно как в Markdown-спеке). Закрывающий — обратная ссылка
# на тот же символ `(?P=fence)` плюс дополнительные символы того же типа:
# ровно то же требование, что и у Markdown-спеки — «не короче открывающего»,
# а не «столько же». Короткий забор ПОСЕРЕДИНЕ блока (например, тройные
# кавычки внутри забора из четырёх) под это требование не подходит и
# закрытием не считается — блок остаётся открытым.
# `|\Z` — единственная альтернатива, которая гарантированно совпадёт, если
# закрывающего забора в тексте больше не найдётся: незакрытый забор считается
# открытым до конца текста, а не пропускается маскировкой вовсе.
_CODE_FENCE = re.compile(
    r"(?ms)^[ \t]*(?P<fence>`{3,}|~{3,})[^\n]*\n"
    r".*?"
    r"(?:^[ \t]*(?P=fence)[`~]*[ \t]*$|\Z)"
)


def mask_code_fences(text: str) -> str:
    """Стирает содержимое ``` и ~~~ блоков пробелами той же длины (переводы
    строк сохраняются), чтобы смещения символов не съезжали — маску можно
    искать регэкспами, рассчитанными на исходный текст, и переиспользовать
    найденные позиции для среза из ОРИГИНАЛА. Маска нужна только для ПОИСКА
    границ — реальное содержимое настоящего раздела вырезается из исходного
    текста, а не из маски, поэтому настоящий пример внутри настоящего раздела
    (например, curl-запрос в шаге демонстрации) не теряется."""
    text = text or ""
    return _CODE_FENCE.sub(
        lambda m: "".join(ch if ch == "\n" else " " for ch in m.group(0)), text)


def has_unclosed_fence(text: str) -> bool:
    """Проверяет, есть ли в тексте незакрытые блоки кода.

    Незакрытый забор — это открывающий забор (``` или ~~~), за которым не
    следует закрывающий забор того же типа и не меньшей длины. Такой забор
    считается открытым до конца текста маскировкой.

    Возвращает True, если найден хотя бы один незакрытый забор.
    """
    text = text or ""
    if not text:
        return False

    # Ищу все матчи забора (включая незакрытые, которые идут до конца текста)
    for m in _CODE_FENCE.finditer(text):
        # Матч соответствует либо закрытому заборе, либо незакрытому до конца
        # текста. Проверяю, дошли ли до конца текста (что означает незакрытый).
        match_end = m.end()
        if match_end == len(text):
            # Этот матч дошёл до конца текста, значит забор незакрыт
            return True

    return False
