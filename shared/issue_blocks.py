"""Размеченные блоки тела Issue — граница между текстом человека и контура.

Контур правит ТОЛЬКО то, что лежит между своими маркерами. Всё остальное тело
принадлежит человеку и не трогается: дописывание в конец плодило бы дубли
разделов при каждом обновлении плана, а перезапись целиком уносила бы
постановку.

Модуль намеренно чистый: ни сети, ни GitHub — как `lifecycle.py`.

Известное ограничение (ревью, находка 2). Текст человека, дословно совпадающий
с форматом маркера (ровно одна пара start/end), от настоящего блока
неотличим — read()/write() работают по разметке, а не по намерению автора
строки, и полностью снять эту двусмысленность нельзя. Смягчают риск, но не
убирают его, два правила ниже: write() отказывает, если ЗАПИСЫВАЕМОЕ
содержимое само похоже на маркер любого из известных модулю блоков (контуру
такая запись никогда не нужна, а значит источником двусмысленности остаётся
только текст человека, не сам контур), и любое число маркеров, кроме ровно
нуля или ровно одной пары, считается повреждённым телом и тоже даёт отказ —
вместо тихой порчи.
"""

import re

MVP_PLAN = "mvp-plan"
GROW = "grow"
# Критерий приёмки, утверждённый человеком. В теле, а не комментарием:
# комментарий теряется в ленте, а критерий должен быть виден в задаче всегда.
HOWTODEMO = "howtodemo"

# Все известные модулю имена блоков. Добавление третьего блока должно пополнить
# этот кортеж — no silent drift.
_ALL_BLOCKS = (MVP_PLAN, GROW, HOWTODEMO)


def _markers(name: str) -> tuple[str, str]:
    return f"<!-- harness:{name}:start -->", f"<!-- harness:{name}:end -->"


def _matched_block(body: str, name: str, start: str, end: str) -> re.Match | None:
    """Проверяет структуру блока `name` в `body` по числу маркеров, а не угадывает.

    Ровно один старт и один конец — блок на месте, возвращается Match на него.
    Ноль обоих — блока нет: для write() это сигнал добавить блок в конец, для
    read() — вернуть None.
    Любая другая комбинация (дубли, старт без конца, конец без старта) — тело
    повреждено. Восстановление добавлением плодит дубли и осиротевшие
    маркеры, а не чинит структуру (ревью, находка 3), поэтому вместо угадывания
    — громкий отказ.
    """
    starts, ends = body.count(start), body.count(end)
    if starts == 0 and ends == 0:
        return None
    if starts == 1 and ends == 1:
        pattern = re.compile(re.escape(start) + r"\n(.*?)\n" + re.escape(end), re.S)
        match = pattern.search(body)
        if match:
            return match
    raise ValueError(
        f"Тело повреждено: блок {name!r} должен встречаться маркерами начала "
        f"и конца ровно по одному разу, а найдено start={starts}, end={ends}. "
        "Чтобы не гадать и не плодить дубли, автоматическая правка отказана."
    )


def read(body: str | None, name: str) -> str | None:
    """Содержимое блока либо None, если блока нет.

    Поднимает ValueError, если структура маркеров блока повреждена (см.
    докстринг модуля и `_matched_block`): склеенный из обрывков результат
    вреднее честного отказа.
    """
    start, end = _markers(name)
    match = _matched_block(body or "", name, start, end)
    return match.group(1) if match else None


def write(body: str | None, name: str, content: str) -> str:
    """Тело с заменённым (или добавленным) блоком.

    Поднимает ValueError в трёх случаях:
    - `content` сам содержит маркер любого из известных модулю блоков (ревью,
      находка 1 и повторное ревью: нежадный поиск следующей записи остановится
      на первом же таком вхождении и обрежет хвост тела без возврата — контуру
      такая запись никогда не нужна, и запись в один блок не должна отравлять
      соседний);
    - структура существующего блока в `body` повреждена (ревью, находка 3, см.
      `_matched_block`).
    """
    start, end = _markers(name)

    # Проверяем маркеры всех известных блоков, не только писавшегося
    for block_name in _ALL_BLOCKS:
        block_start, block_end = _markers(block_name)
        if block_start in content or block_end in content:
            raise ValueError(
                f"Содержимое блока {name!r} не должно содержать маркеры блока "
                f"{block_name!r} ({block_start!r} / {block_end!r}) — запись в один "
                "блок не должна отравлять соседний и обрезать тело молча."
            )

    body = body or ""
    block = f"{start}\n{content}\n{end}"
    match = _matched_block(body, name, start, end)
    if match:
        return f"{body[:match.start()]}{block}{body[match.end():]}"
    tail = "" if body.endswith("\n") else "\n"
    return f"{body}{tail}\n{block}\n"


def strip(body: str | None, name: str) -> str:
    """Тело без блока `name` целиком, вместе с обоими маркерами.

    Блока нет — тело возвращается как было (ничего не вырезаем).

    Ревью, находка 1 (Important). До этой функции `worker/activities.py` вырезал
    пустой утверждённый блок HowToDemo самодельной регэксп-строкой с буквальными
    `<!-- harness:{name}:start -->` / `:end -->` — единственное место во всём
    репозитории, где формат маркеров был захардкожен ВНЕ этого модуля. Смени
    формат в `_markers()` — и тот дубликат молча перестал бы совпадать: вырезание
    стало бы пустой операцией, а пустой блок снова прилипал бы хвостом к разделу
    человека, то есть вернулся бы ровно тот дефект, ради которого писалась
    приоритетность блока над разделом. `strip()` переиспользует `_matched_block`
    — тот же код, что уже используют read()/write() и что покрыт тестами на
    структуру маркеров, — а не заводит вторую регэксп-вырезку.

    Поднимает ValueError, если структура маркеров блока повреждена (см.
    докстринг модуля и `_matched_block`) — молчаливо резать повреждённое тело
    так же плохо, как молчаливо резать по неверному формату.
    """
    start, end = _markers(name)
    body = body or ""
    match = _matched_block(body, name, start, end)
    if not match:
        return body
    return body[:match.start()] + body[match.end():]
