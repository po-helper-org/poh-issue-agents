"""Точка подключения агента разработки к Harness.

Стадия «Разработка» живёт в своём репозитории (`po-helper-org/poh-developer-agents`)
и ставится в образ воркера пакетом. Harness не знает ни как устроен прогон
агента, ни чем разбирается красный тест, ни как считается круг правок — он даёт
стадии ровно пять вещей, объявленных её портами:

1. **Трекер и репозиторий кода** — тот же клиент провайдера, что у остальных
   стадий, плюс клон рабочей копии. Клон отдаётся ОДНИМ методом: токен обязан
   остаться по эту сторону границы, рядом с агентом, исполняющим чужой код, ему
   делать нечего.
2. **Именованные участки тела задачи** — секция находок и сценарий приёмки.
3. **Индекс кода** и 4. **слой памяти** — оба необязательные: не подключены,
   агент работает без них.
5. **Телеметрия** — ради одного отказа, потерянных находок агента.

Обратной зависимости нет: `poh_developer` не импортирует из Harness ничего.

Адаптеры делегируют МОДУЛЮ, а не связываются с его функциями при сборке:
подменённая в тесте `github_client.post_comment` обязана дойти до стадии, иначе
три десятка тестов контура проверяли бы подмену, которая никуда не подключена.
"""

import forge
# Историческое имя клиента провайдера: так его знают активности и три десятка
# тестовых файлов, которые подменяют в нём методы. Порт обязан звать ТОТ ЖЕ
# объект — диспетчер провайдеров, а не `worker/github_client.py` под ним, иначе
# подмена в тесте до стадии не доходит и прогон уходит в живую сеть.
github_client = forge

from poh_developer import integration as developer
from shared import howtodemo, issue_blocks, memory, repowise, sentry_setup


class _ModuleAdapter:
    """Порт поверх модуля Harness: всё берётся из модуля в момент вызова.

    `__getattr__`, а не перечисление методов: порт и модуль совпадают именами,
    и список посередине пришлось бы править дважды на каждый новый метод — а
    забытая правка проявилась бы `AttributeError` на живом прогоне.
    """

    def __init__(self, module):
        self._module = module

    def __getattr__(self, name):
        return getattr(self._module, name)


class _GitHub(_ModuleAdapter):
    """Трекер, репозиторий кода и клон рабочей копии."""

    def clone_repo(self, repo: str, dest: str, branch: str | None = None) -> None:
        """Shallow-клон целевого репозитория.

        Живёт здесь, а не в пакете, потому что собирает команду `git` вокруг
        токена: адрес, пара для credential-хелпера и сам токен. Стадии из этого
        не нужно ничего — ей нужен готовый каталог.

        Импорт внутри вызова: `activities` тянет этот модуль через воркер, и
        связывание на уровне модуля замкнуло бы круг.
        """
        import activities

        activities._clone_repo(repo, dest, branch)


class _IssueBlocks(_ModuleAdapter):
    """Именованные участки тела задачи."""

    def howtodemo_block(self, body: str) -> str:
        """Сценарий приёмки — либо из размеченного блока, либо из раздела тела.

        Отдельным методом, потому что правило выбора между ними — словарь
        Harness: у блока приоритет над разделом, и знать это стадии незачем.
        """
        return howtodemo.read(body)


def install() -> None:
    """Подставить реализации портов. Зовётся один раз на старте воркера."""
    developer.install(
        github=_GitHub(github_client),
        issue_blocks=_IssueBlocks(issue_blocks),
        repowise=_ModuleAdapter(repowise),
        memory=_ModuleAdapter(memory),
        telemetry=_ModuleAdapter(sentry_setup),
    )
